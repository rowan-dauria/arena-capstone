"""Write configs/prices.yaml from OpenRouter's public price list.

    uv run python scripts/update_prices.py            # models in every configs/*.yaml
    uv run python scripts/update_prices.py configs/exp1.yaml

Collects the model of every role in the given stage configs (stages whose ${VARS}
are not set are skipped with a note), looks up `openrouter/...` models at
https://openrouter.ai/api/v1/models (no key needed), and merges them into
configs/prices.yaml with today's date. Non-OpenRouter models are kept as they
are; add their prices by hand (USD per million tokens). Rerun before the pilot
and before Experiment 1: prices drift.
"""

from __future__ import annotations

import json
import sys
import urllib.request
from datetime import date
from pathlib import Path

import yaml
from dotenv import load_dotenv

from swarm_emulator import repo_path
from swarm_emulator.costs import PRICES, load_prices, openrouter_price
from swarm_emulator.stage import load_stage, role_model

URL = "https://openrouter.ai/api/v1/models"


def stage_models(paths: list[Path]) -> set[str]:
    models: set[str] = set()
    for path in paths:
        try:
            models |= {role_model(m) for m in load_stage(path)["roles"].values()}
        except KeyError as ex:
            print(f"skip {path.name}: {ex.args[0]}", file=sys.stderr)
    return models


def main() -> int:
    load_dotenv(override=False)
    paths = [Path(p) for p in sys.argv[1:]] or sorted(repo_path("configs").glob("*.yaml"))
    paths = [p for p in paths if p.name != Path(PRICES).name]
    models = stage_models(paths)

    with urllib.request.urlopen(URL, timeout=30) as resp:
        listing = json.load(resp)["data"]
    pricing = {m["id"]: m.get("pricing", {}) for m in listing}

    table = load_prices(repo_path(PRICES))
    missing = []
    for model in sorted(models):
        name = model.removeprefix("openrouter/")
        if model.startswith("openrouter/") and name in pricing:
            table.models[model] = openrouter_price(pricing[name])
        elif model not in table.models:
            missing.append(model)
    table.fetched = date.today().isoformat()

    header = (
        "# USD per million tokens, per model id as used in configs/*.yaml.\n"
        "# Generated by scripts/update_prices.py (OpenRouter entries); hand-added\n"
        "# entries for other providers are kept. Rerun before pilot and Exp 1.\n"
    )
    body = yaml.safe_dump(table.model_dump(), sort_keys=True)
    repo_path(PRICES).write_text(header + body)
    print(f"wrote {PRICES}: {len(table.models)} model(s), fetched {table.fetched}")
    for m in missing:
        print(f"NO PRICE  {m}  (not on OpenRouter; add it by hand)", file=sys.stderr)
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
