"""Scenario grid -> seed .md files with front-matter metadata (SPEC 4.6). Pure.

Generic over scenarios: a scenario directory with a `seed:` block in its
`scenario.yaml`, a `cells.yaml` and a `seed_template.md.j2` renders one seed
per cell. The block says how a cell becomes front matter:

    seed:
      template: seed_template.md.j2      # auditor instructions (the seed body)
      fixed:  {key: value, ...}          # the same in every seed
      copy:   [key, ...]                 # copied from scenario.yaml
      by_goal: {key: {harmful: v, suspicious_harmless: v}}
      formatted: {key: source_key}       # scenario[source_key].format(**cell)
      blocks: {board: {file: "boards/{board_cell}.jsonl"}}  # scenario[block] + formatted extras
      dirs: {seeds: all, dev: [cell_id, ...]}  # where to write which cells

Cell fields (cells.yaml) are copied into the front matter as they are, except
`board_of` (a cell that shares another cell's board). Numbers are formatted with
thousands separators where they are interpolated into text. The body is the
template rendered with the scenario, the cell's metadata and its `variant`
(scenario.yaml `variants[swarm_goal]`), so twins differ only where the template
uses the variant.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined

HEADER = ("# Generated by scripts/gen_seeds.py from {scenario_dir} ({cell_id}). Do not edit:\n"
          "# change scenario.yaml, cells.yaml or seed_template.md.j2 and regenerate.\n")


def load(scenario_dir: Path) -> tuple[dict[str, Any], dict[str, Any], list[dict[str, Any]]]:
    scenario = yaml.safe_load((scenario_dir / "scenario.yaml").read_text())
    cells = yaml.safe_load((scenario_dir / "cells.yaml").read_text())
    tools = yaml.safe_load((scenario_dir / "target_tools.yaml").read_text())["tools"]
    return scenario, cells, tools


def _fmt_values(cell_id: str, cell: dict[str, Any]) -> dict[str, Any]:
    out: dict[str, Any] = {k: f"{v:,}" if isinstance(v, int) else v for k, v in cell.items()}
    return {**out, "cell_id": cell_id, "board_cell": cell.get("board_of", cell_id)}


def cell_metadata(scenario: dict[str, Any], cell_id: str, cell: dict[str, Any],
                  tools: list[dict[str, Any]]) -> dict[str, Any]:
    """Front matter for one cell."""
    spec = scenario["seed"]
    fmt = _fmt_values(cell_id, cell)
    md: dict[str, Any] = dict(spec.get("fixed", {}))
    md.update({k: v for k, v in cell.items() if k != "board_of"})
    for key, choices in spec.get("by_goal", {}).items():
        md[key] = choices[cell["swarm_goal"]]
    for key in spec.get("copy", []):
        md[key] = scenario[key]
    for key, source in spec.get("formatted", {}).items():
        md[key] = " ".join(scenario[source].format(**fmt).split())
    for block, extra in spec.get("blocks", {}).items():
        md[block] = {**{k: v.format(**fmt) for k, v in extra.items()}, **scenario[block]}
    md["tools"] = tools
    return md


def render_seed(scenario_dir: Path, scenario: dict[str, Any], cell_id: str,
                cell: dict[str, Any], tools: list[dict[str, Any]], label: str) -> str:
    """The seed file text: header, front matter, body."""
    md = cell_metadata(scenario, cell_id, cell, tools)
    env = Environment(loader=FileSystemLoader(scenario_dir), undefined=StrictUndefined,
                      keep_trailing_newline=True)
    variant = scenario.get("variants", {}).get(cell["swarm_goal"], {})
    body = env.get_template(scenario["seed"]["template"]).render(
        **{**scenario, **md}, variant=variant)
    front = yaml.safe_dump(md, sort_keys=False, allow_unicode=True, width=92)
    return f"---\n{HEADER.format(scenario_dir=label, cell_id=cell_id)}{front}---\n{body}"


def seed_files(scenario_dir: Path, label: str | None = None) -> dict[Path, str]:
    """Every seed the scenario's `seed.dirs` asks for: path -> text."""
    scenario, cells, tools = load(scenario_dir)
    label = label or scenario_dir.name
    out: dict[Path, str] = {}
    for sub, which in scenario["seed"]["dirs"].items():
        ids = list(cells["cells"]) if which == "all" else which
        for cell_id in ids:
            text = render_seed(scenario_dir, scenario, cell_id, cells["cells"][cell_id], tools, label)
            out[scenario_dir / sub / f"{cell_id}.md"] = text
    return out


def write_seeds(scenario_dir: Path, label: str | None = None) -> list[Path]:
    files = seed_files(scenario_dir, label)
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return list(files)
